#!/usr/bin/env python3
"""gen_builder — generate a document builder script from a component library TTL.

The library is a DDS Document whose components are reusable prototypes (see
library/planning-components.ttl). Each prototype (found at any depth, IRI .../<lib-doc>/<name>)
becomes one builder method <name>(...). The generated script needs only rdflib and writes a
document ABox (Turtle) with ids, hasChild and hasOrder filled in; validate it with validate.py.

Usage:
  python3 gen_builder.py LIBRARY.ttl -o build_planning.py
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from rdflib import Graph  # noqa: E402

from dds_lib.graph import DDS, load_data  # noqa: E402
from dds_lib.model import children, component_kind, documents, local_name, title_of  # noqa: E402
from rdflib.namespace import RDF  # noqa: E402

LEAF = {"Heading", "Paragraph", "ListItem", "TableCell"}
CONTAINER = {"Section", "List", "Table", "TableRow"}

CORE = '''"""Generated by gen_builder.py from {library}. Do not edit; edit the library and regenerate.

Usage:
    from {module} import Doc
    d = Doc("my-id", "문서 제목", lang="ko")
    d.add(d.section("overview", d.heading("overview-title", "개요"),
                    d.description("overview-desc", "...")))
    d.write("my.ttl")      # then: python3 scripts/validate.py my.ttl
"""
from rdflib import Graph, Literal, Namespace, URIRef
from rdflib.namespace import RDF, SKOS

BASE = "{base}"
DDS = Namespace("https://example.org/ontology/dds#")
DESIGN_SYSTEM = "{design_system}"
_NS = {{k: Namespace(BASE + k + "/") for k in
       ("structure", "semantic", "presentation", "design", "doc", "component")}}


class Node:
    def __init__(self, id, structure, sem=(), pres=None, content=None, children=(), ordered=None):
        self.id, self.structure, self.sem, self.pres = id, structure, tuple(sem), pres
        self.content, self.children, self.ordered = content, list(children), ordered


class Doc:
    def __init__(self, id, title, lang="ko", design_system=DESIGN_SYSTEM):
        self.id, self.title, self.lang, self.ds = id, title, lang, design_system
        self.roots = []

    def add(self, *nodes):
        self.roots.extend(nodes)
        return self

    def _items(self, prefix, items, structure, default):
        """Plain strings become default nodes with positional ids {{prefix}}{{n}}."""
        return [it if isinstance(it, Node) else Node(f"{{prefix}}{{n}}", structure, *default, content=it)
                for n, it in enumerate(items, 1)]

    def write(self, path=None):
        g = Graph()
        for k, ns in _NS.items():
            g.bind(k, ns)
        g.bind("dds", DDS)
        g.bind("skos", SKOS)
        doc = _NS["doc"][self.id]
        g.add((doc, RDF.type, DDS.Document))
        g.add((doc, SKOS.prefLabel, Literal(self.title, lang=self.lang)))
        g.add((doc, DDS.usesDesignSystem, _NS["design"][self.ds]))
        seen = set()

        def emit(node, order, parent):
            if node.id in seen:
                raise ValueError(f"duplicate component id: {{node.id}}")
            seen.add(node.id)
            iri = _NS["component"][f"{{self.id}}/{{node.id}}"]
            g.add((iri, RDF.type, DDS.Component))
            g.add((iri, DDS.hasStructure, _NS["structure"][node.structure]))
            for s in node.sem:
                g.add((iri, DDS.hasSemantic, _NS["semantic"][s]))
            if node.pres:
                g.add((iri, DDS.hasPresentation, _NS["presentation"][node.pres]))
            g.add((iri, DDS.hasOrder, Literal(order)))
            if node.ordered is not None:
                g.add((iri, DDS.ordered, Literal(bool(node.ordered))))
            if node.content is not None:
                g.add((iri, DDS.hasContent, Literal(node.content, lang=self.lang)))
            g.add(((parent, DDS.hasChild, iri) if parent else (doc, DDS.hasComponent, iri)))
            for i, c in enumerate(node.children, 1):
                emit(c, i, iri)

        for i, r in enumerate(self.roots, 1):
            emit(r, i, None)
        if path:
            g.serialize(destination=str(path), format="turtle")
        return g

'''


def _fn_leaf(name, s, sem, pres):
    return f'''    def {name}(self, id, content):
        return Node(id, {s!r}, {sem!r}, {pres!r}, content=content)

'''


def _fn_section(name, s):
    return f'''    def {name}(self, id, *children):
        return Node(id, {s!r}, children=children)

'''


def _fn_list(name, s, ordered, item):
    st, sem, pres = item
    return f'''    def {name}(self, id, *items, ordered={ordered!r}):
        return Node(id, {s!r}, children=self._items(id + "-i", items, {st!r}, ({sem!r}, {pres!r})), ordered=ordered)

'''


def _fn_table(name, s, row, cell):
    rs, rsem, rpres = row
    cs, csem, cpres = cell
    return f'''    def {name}(self, id, *rows):
        out = []
        for n, r in enumerate(rows, 1):
            if isinstance(r, Node):
                out.append(r)
            else:
                rid = f"{{id}}-r{{n}}"
                out.append(Node(rid, {rs!r}, {rsem!r}, {rpres!r}, children=self._items(rid + "-c", r, {cs!r}, ({csem!r}, {cpres!r}))))
        return Node(id, {s!r}, children=out)

'''


def _fn_row(name, s, cell):
    cs, csem, cpres = cell
    return f'''    def {name}(self, id, *cells):
        return Node(id, {s!r}, children=self._items(id + "-c", cells, {cs!r}, ({csem!r}, {cpres!r})))

'''


def build(lib: Path, module: str) -> str:
    g = load_data([lib])
    docs = [d for d in documents(g) if str(d).startswith(str(DDS)) is False and any(g.objects(d, DDS.hasComponent))]
    if len(docs) != 1:
        raise SystemExit(f"error: library must hold exactly one Document with components, found {len(docs)}")
    doc = docs[0]
    ds = local_name(g.value(doc, DDS.usesDesignSystem))
    base = str(doc).rsplit("doc/", 1)[0]
    protos = {}  # name -> (comp, kind)

    def walk(c):
        protos[local_name(c).split("/")[-1] if "/" in str(c) else local_name(c)] = (c, component_kind(g, c))
        for ch in children(g, c):
            walk(ch)

    for r in g.objects(doc, DDS.hasComponent):
        walk(r)

    def attrs(c):
        st = local_name(g.value(c, DDS.hasStructure))
        sem = tuple(sorted(local_name(s) for s in g.objects(c, DDS.hasSemantic)))
        pr = g.value(c, DDS.hasPresentation)
        return st, sem, (local_name(pr) if pr is not None else None)

    def plain(kind):
        for name, (c, k) in sorted(protos.items()):
            if k == kind and not attrs(c)[1] and attrs(c)[2] is None:
                return attrs(c)
        for name, (c, k) in sorted(protos.items()):
            if k == kind:
                return (attrs(c)[0], (), None)
        return (kind, (), None)

    out = CORE.format(library=lib.name, module=module, base=base, design_system=ds)
    for name, (c, kind) in sorted(protos.items(), key=lambda kv: str(kv[1][0])):
        st, sem, pres = attrs(c)
        if kind in LEAF:
            out += _fn_leaf(name, st, sem, pres)
        elif kind == "Section":
            out += _fn_section(name, st)
        elif kind == "List":
            o = g.value(c, DDS.ordered)
            out += _fn_list(name, st, bool(o) if o is not None else False, plain("ListItem"))
        elif kind == "Table":
            out += _fn_table(name, st, plain("TableRow"), plain("TableCell"))
        elif kind == "TableRow":
            out += _fn_row(name, st, plain("TableCell"))
    return out.rstrip() + "\n"


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("library", type=Path)
    ap.add_argument("-o", "--output", type=Path, required=True)
    a = ap.parse_args(argv)
    code = build(a.library, a.output.stem)
    a.output.write_text(code, encoding="utf-8")
    compile(code, str(a.output), "exec")
    print(f"wrote {a.output}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
